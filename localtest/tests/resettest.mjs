import { chromium } from "playwright";
import { execSync } from "node:child_process";
const BASE = "http://127.0.0.1:3100", T = "october-special-2026";
let fails = 0; const ok = (c, m) => (console.log(`${c ? "PASS" : "FAIL"}  ${m}`), c || fails++);
const q = (sql) => execSync(`psql -h 127.0.0.1 -p 5433 -U postgres -qtA -c "${sql}"`).toString().trim();
const tid = q("select id from tournaments where slug='october-special-2026'");
const count = () => q(`select (select count(*) from hole_entries e join rounds r on r.id=e.round_id where r.tournament_id='${tid}') || ',' || (select count(*) from posts where tournament_id='${tid}') || ',' || (select count(*) from ai_pieces where tournament_id='${tid}') || ',' || (select count(*) from comments where tournament_id='${tid}')`);
const keep = () => q(`select (select count(*) from players where tournament_id='${tid}') || ',' || (select count(*) from rounds where tournament_id='${tid}' and course_guide is not null) || ',' || (select count(*) from subscribers where tournament_id='${tid}') || ',' || (select coalesce(string_agg(handicap_rule::text,''),'') from rounds where tournament_id='${tid}' and number=1)`);
const other = () => q("select count(*) from hole_entries e join rounds r on r.id=e.round_id join tournaments t on t.id=r.tournament_id where t.slug<>'october-special-2026'");
let cookie = "";
const post = async (path, body) => { const r = await fetch(BASE + path, { method: "POST", headers: { "content-type": "application/json", ...(cookie ? { cookie } : {}) }, body: JSON.stringify({ t: T, ...body }) }); const sc = r.headers.get("set-cookie"); if (sc) cookie = sc.split(";")[0]; return { status: r.status, j: await r.json().catch(() => ({})) }; };
await post("/api/login", { mode: "organiser", pin: "1234" });
const st = (await post("/api/admin", { action: "state" })).j.state;
const r1 = st.rounds.find((r) => r.number === 1);
await post("/api/admin", { action: "saveRound", round: { id: r1.id, handicap_rule: { mode: "manual", shots: { neil: 4 } } } });
for (let h = 1; h <= 9; h++) await post("/api/score", { roundId: r1.id, hole: h, scores: { oisin: { gross: 4 }, neil: { gross: 5 } } });
await post("/api/admin", { action: "aiGenerate", kind: "preview", roundId: r1.id });
await post("/api/admin", { action: "addSubscribers", text: "me@example.ie" });
await fetch(BASE + "/api/comments", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ t: T, name: "Fan", body: "Go on!", roundId: r1.id }) });
const before = count(), kept = keep(), oth = other();
console.log("     before:", before, "| kept:", kept, "| other tournament entries:", oth);
ok(!before.startsWith("0,"), "test data exists");
ok((await post("/api/admin", { action: "resetTestData", confirm: "nope" })).status === 400, "needs RESET typed");
const anon = await fetch(BASE + "/api/admin", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ t: T, action: "resetTestData", confirm: "RESET" }) });
ok(anon.status >= 401, "only the organiser can reset");
// through the admin screen
const b = await chromium.launch(); const pg = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
await pg.request.post(`${BASE}/api/login`, { data: { t: T, mode: "organiser", pin: "1234" } });
await pg.goto(`${BASE}/t/${T}/admin`, { waitUntil: "networkidle" });
await pg.getByRole("link", { name: /Settings and test data/ }).click();
const btn = pg.getByRole("button", { name: "Reset test data" });
ok(await btn.isDisabled(), "button locked until RESET is typed");
await pg.getByLabel("Type RESET to confirm").fill("reset");
await btn.click();
await pg.getByText(/Reset done/).waitFor({ timeout: 15000 });
await pg.locator("section.panel").filter({ hasText: "Type RESET" }).screenshot({ path: "/var/tmp/ospg/shots/reset.png" });
await b.close();
ok(count() === "0,0,0,0", `scores, posts, AI pieces, comments cleared (${count()})`);
ok(keep() === kept, "players, guides, email list and handicaps kept");
ok(q(`select string_agg(distinct status, ',') from rounds where tournament_id='${tid}'`) === "upcoming", "rounds back to upcoming");
ok(other() === oth, "other tournaments untouched");
console.log(fails ? `\n${fails} FAILED` : "\nALL PASSED"); process.exit(fails ? 1 : 0);
